/**
 * 「转移后原作者会怎样」这句忠告的唯一出处 —— 单任务弹窗与批量弹窗共用。
 *
 * 这是整个交接功能里最会被追问的一句话（后端 notify_service 的两条通知正文里也是同一句，
 * 那边同样只写一次）。分开写两份的结果是：改一次口径要找四处，而措辞漂了不会有任何测试
 * 变红——本功能第一版就已经漂出了「仍可见、可运行」与「仍看得到、跑得动」两种说法。
 *
 * 人称在单任务与批量两处的算法不同（单任务能二选一说「你/原作者」，批量的原作者可能好几个，
 * 只能具名），所以主语由调用方给，这里只负责后果与补救办法。
 */
export default function TransferConsequence({
  subject,
  pron,
  plural,
}: {
  /** 谁会失去编辑权：单任务是「你」/「原作者」，批量是「原作者们」 */
  subject: string;
  /** 指代该主语的人称，用在「除非X是团队管理员」里 */
  pron: string;
  plural?: boolean;
}) {
  const it = plural ? "这些任务" : "这个任务";
  return (
    <>
      {subject}仍是团队成员，<b>仍可见、可运行</b>
      {it}，但不再有编辑权（除非{pron}是本团队的团队管理员）。确有需要时，由团队管理员在
      「任务编辑权」里单独授予。
    </>
  );
}
