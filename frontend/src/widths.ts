/** 运行记录 / 取数这条链路上的抽屉与弹窗宽度。
 *
 * **不是全站注册表** —— 其余弹窗(任务编辑器、授权、订阅者等)仍是各自调用点的字面量,
 * 别以为在这儿找不到就等于没有。收进来的是同屏会互相打架的那几个:此前结果预览弹窗 900
 * 比它所在的抽屉 860 还宽,谁都没注意到,因为两个数字隔着三个文件。
 *
 * 写成 `min(上限, 94vw)` 而不是定死的像素:大屏放得开,小屏不溢出。视口上限这条策略由
 * cap() 独占,改 94 → 92 只动一处;每项自己只管「最宽到哪」这一个数。
 *
 * 注意:宽度一旦跟着视口走,「这几列本来就排得下」这类判断就不再成立 —— 表格该留的横向
 * 滚动兜底不能省(见 RunRecordsPanel 的 scroll 设置)。
 */
const cap = (px: number) => `min(${px}px, 94vw)`;

export const DRAWER = {
  /** 运行记录(full 形态):列宽预算见 RunRecordsPanel 的 WIDTHS.full,留足余量 */
  records: cap(1180),
  /** 取数抽屉·填参态:要装下内嵌的 compact 运行记录(预算见同一处) */
  run: cap(620),
  /** 取数抽屉·预览态 */
  runPreview: cap(1040),
};

export const MODAL = {
  /** 结果预览:列数由用户的 SQL 决定,给到最宽 */
  preview: cap(1100),
  /** 执行 SQL */
  sql: cap(900),
  /** 本次运行参数:两列的小表 */
  params: cap(560),
};
